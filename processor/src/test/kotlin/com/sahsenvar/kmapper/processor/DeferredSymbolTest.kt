package com.sahsenvar.kmapper.processor

import com.google.devtools.ksp.processing.CodeGenerator
import com.google.devtools.ksp.processing.Dependencies
import com.google.devtools.ksp.processing.Resolver
import com.google.devtools.ksp.processing.SymbolProcessor
import com.google.devtools.ksp.processing.SymbolProcessorEnvironment
import com.google.devtools.ksp.processing.SymbolProcessorProvider
import com.google.devtools.ksp.symbol.KSAnnotated
import com.tschuchort.compiletesting.JvmCompilationResult
import com.tschuchort.compiletesting.KotlinCompilation
import com.tschuchort.compiletesting.SourceFile
import io.kotest.core.spec.style.BehaviorSpec
import io.kotest.matchers.shouldBe
import io.kotest.matchers.string.shouldContain
import org.jetbrains.kotlin.compiler.plugin.ExperimentalCompilerApi

/**
 * A mapping class that depends on a type another processor generates in the same round does not
 * validate in that round. It must be deferred and mapped in a later round, never dropped: dropping
 * it made KSP succeed with the mapper missing, and that incomplete output was then build-cached.
 */
class DeferredSymbolTest :
    BehaviorSpec({

        given("a @MapTo class whose field type is generated by another processor in round 1") {
            val (result, compilation) =
                compileWithGeneratedMoney(
                    """
                    import com.sahsenvar.kmapper.annotations.MapTo
                    data class PriceDomainModel(val id: String, val money: GeneratedMoney)
                    @MapTo(PriceDomainModel::class)
                    data class PriceDataModel(val id: String, val money: GeneratedMoney)
                    fun usesMapper(price: PriceDataModel): PriceDomainModel = price.toPriceDomainModel()
                    """.trimIndent(),
                )

            `when`("the mappers are generated") {
                then("the class is mapped in a later round instead of being dropped") {
                    result.exitCode shouldBe KotlinCompilation.ExitCode.OK
                    compilation.generatedFile("PriceDataModelMappers.kt") shouldContain "fun PriceDataModel.toPriceDomainModel()"
                }
            }
        }

        given("a @MapFrom class whose field type is generated by another processor in round 1") {
            val (result, compilation) =
                compileWithGeneratedMoney(
                    """
                    import com.sahsenvar.kmapper.annotations.MapFrom
                    data class PriceDataModel(val id: String, val money: GeneratedMoney)
                    @MapFrom(PriceDataModel::class)
                    data class PriceDomainModel(val id: String, val money: GeneratedMoney)
                    """.trimIndent(),
                )

            `when`("the reverse mapper is generated") {
                then("the class is mapped in a later round instead of being dropped") {
                    result.exitCode shouldBe KotlinCompilation.ExitCode.OK
                    compilation.generatedFile("PriceDataModelMappers.kt") shouldContain "fun PriceDataModel.toPriceDomainModel()"
                }
            }
        }

        given("a valid @MapTo class whose TARGET has a field of a generated type") {
            val (result, compilation) =
                compileWithGeneratedMoney(
                    """
                    import com.sahsenvar.kmapper.annotations.MapTo
                    data class PriceDomainModel(val id: String, val money: GeneratedMoney? = null)
                    @MapTo(PriceDomainModel::class)
                    data class PriceDataModel(val id: String)
                    """.trimIndent(),
                )

            `when`("the mapper is generated") {
                then("the target is analyzed only once its field type exists") {
                    result.exitCode shouldBe KotlinCompilation.ExitCode.OK
                    compilation.generatedFile("PriceDataModelMappers.kt") shouldContain "fun PriceDataModel.toPriceDomainModel()"
                }
            }
        }

        given("a resolvable @MapTo class next to one that has to wait for a generated type") {
            val (result, compilation) =
                compileWithGeneratedMoney(
                    """
                    import com.sahsenvar.kmapper.annotations.MapTo
                    data class UserDomainModel(val id: String)
                    @MapTo(UserDomainModel::class)
                    data class UserDataModel(val id: String)
                    data class PriceDomainModel(val money: GeneratedMoney)
                    @MapTo(PriceDomainModel::class)
                    data class PriceDataModel(val money: GeneratedMoney)
                    """.trimIndent(),
                )

            `when`("the batch is deferred") {
                then("both mappers are generated exactly once") {
                    result.exitCode shouldBe KotlinCompilation.ExitCode.OK
                    compilation.generatedFile("UserDataModelMappers.kt") shouldContain "fun UserDataModel.toUserDomainModel()"
                    compilation.generatedFile("PriceDataModelMappers.kt") shouldContain "fun PriceDataModel.toPriceDomainModel()"
                }
            }
        }

        given("a @KMapperConfig converter whose type pair uses a generated type") {
            val (result, compilation) =
                compileWithGeneratedMoney(
                    """
                    import com.sahsenvar.kmapper.annotations.KMapperConfig
                    import com.sahsenvar.kmapper.annotations.MapTo
                    import com.sahsenvar.kmapper.converter.MapTypeConverter

                    object MoneyConverter : MapTypeConverter<Long, GeneratedMoney>(Long::class, GeneratedMoney::class) {
                        override fun convertTo(source: Long): GeneratedMoney = GeneratedMoney(source)

                        override fun convertFrom(target: GeneratedMoney): Long = target.amount
                    }

                    @KMapperConfig(converters = [MoneyConverter::class])
                    object MappingConfig

                    data class PriceDomainModel(val money: GeneratedMoney)

                    @MapTo(PriceDomainModel::class)
                    data class PriceDataModel(val money: Long)
                    """.trimIndent(),
                )

            `when`("the mapper is generated in the later round") {
                then("the converter is registered and used") {
                    result.exitCode shouldBe KotlinCompilation.ExitCode.OK
                    compilation.generatedFile("PriceDataModelMappers.kt") shouldContain "MoneyConverter.convertTo(it)"
                }
            }
        }

        given("a @MapTo class that first appears in round 2, after @KMapperConfig was processed in round 1") {
            val (result, compilation) =
                compile(
                    sources =
                    listOf(
                        SourceFile.kotlin(
                            "Config.kt",
                            """
                                import com.sahsenvar.kmapper.annotations.KMapperConfig
                                import com.sahsenvar.kmapper.converter.MapTypeConverter

                                object OctalConverter : MapTypeConverter<String, Int>(String::class, Int::class) {
                                    override fun convertTo(source: String): Int = source.toInt(8)

                                    override fun convertFrom(target: Int): String = target.toString(8)
                                }

                                @KMapperConfig(converters = [OctalConverter::class])
                                object MappingConfig

                                data class JobDomainModel(val occupation: Int)
                            """.trimIndent(),
                        ),
                    ),
                    kspOptions = emptyMap(),
                    additionalProviders =
                    listOf(
                        SourceGeneratingProcessorProvider(
                            fileName = "GeneratedJob",
                            content =
                            """
                                    import com.sahsenvar.kmapper.annotations.MapTo
                                    @MapTo(JobDomainModel::class)
                                    data class JobDataModel(val occupation: String)
                            """.trimIndent(),
                        ),
                    ),
                )

            `when`("the mapper is generated in round 2") {
                then("the converter registered in round 1 is still known") {
                    result.exitCode shouldBe KotlinCompilation.ExitCode.OK
                    compilation.generatedFile("JobDataModelMappers.kt") shouldContain "OctalConverter.convertTo(it)"
                }
            }
        }

        given("a @MapTo class whose field type never comes into existence") {
            val (result, _) =
                compile(
                    SourceFile.kotlin(
                        "Broken.kt",
                        """
                        import com.sahsenvar.kmapper.annotations.MapTo
                        data class BrokenDomainModel(val value: String)
                        @MapTo(BrokenDomainModel::class)
                        data class BrokenDataModel(val value: MissingType)
                        """.trimIndent(),
                    ),
                )

            `when`("no round can resolve it") {
                then("KMapper reports the unresolvable class instead of finishing silently") {
                    result.exitCode shouldBe KotlinCompilation.ExitCode.COMPILATION_ERROR
                    result.messages shouldContain "KMapper generated no mappers for this module"
                    result.messages shouldContain "BrokenDataModel"
                }
            }
        }
    })

private const val GENERATED_MONEY = "data class GeneratedMoney(val amount: Long)\n"

private fun compileWithGeneratedMoney(source: String): Pair<JvmCompilationResult, KotlinCompilation> = compile(
    sources = listOf(SourceFile.kotlin("Models.kt", source)),
    kspOptions = emptyMap(),
    additionalProviders = listOf(SourceGeneratingProcessorProvider("GeneratedMoney", GENERATED_MONEY)),
)

/** Stand-in for a second KSP processor: writes one Kotlin file in its first round. */
private class SourceGeneratingProcessorProvider(
    private val fileName: String,
    private val content: String,
) : SymbolProcessorProvider {
    override fun create(environment: SymbolProcessorEnvironment): SymbolProcessor = SourceGeneratingProcessor(environment.codeGenerator, fileName, content)
}

private class SourceGeneratingProcessor(
    private val codeGenerator: CodeGenerator,
    private val fileName: String,
    private val content: String,
) : SymbolProcessor {
    private var generated = false

    override fun process(resolver: Resolver): List<KSAnnotated> {
        if (generated) return emptyList()
        generated = true
        codeGenerator.createNewFile(Dependencies(aggregating = true), "", fileName).bufferedWriter().use { writer ->
            writer.write(content)
        }
        return emptyList()
    }
}
